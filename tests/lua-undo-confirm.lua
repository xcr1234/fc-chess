local S=require('game.session')
local B=require('game.board')
require('app.log').enabled=false
local failures=0
local function check(name,fn)
 local ok,err=pcall(fn);print((ok and 'PASS ' or 'FAIL ')..name..(ok and '' or ': '..tostring(err)))
 if not ok then failures=failures+1 end
end
local function thinking()
 local s=S.new();S.start(s,'difficult');s.aiInput={computeSeconds=.2,waitSeconds=.2,replySequence={{0,3,0,4}}}
 S.square(s,55);S.square(s,46);return s
end
check('undo button asks first and blocks squares and other actions without consuming history',function()
 local s=thinking();local board=B.key(s.board,s.turn,s.custom);local version=s.version
 S.action(s,'UndoButton');assert(s.modal=='undo' and s.moves==1 and #s.history==1)
 S.square(s,57);S.action(s,'ResignButton');S.action(s,'UndoButton')
 assert(s.modal=='undo' and s.version==version and B.key(s.board,s.turn,s.custom)==board)
 S.action(s,'ConfirmNo');assert(not s.modal and s.moves==1 and #s.history==1)
end)
check('declining a ready reply releases it exactly once',function()
 local s=thinking();S.action(s,'UndoButton');S.update(s,.3);S.update(s,.3)
 assert(s.ready and s.moves==1 and #s.history==1 and s.modal=='undo')
 S.action(s,'ConfirmNo');assert(not s.modal and s.moves==2 and s.turn=='red')
 S.action(s,'ConfirmNo');S.update(s,20);assert(s.moves==2)
end)
check('confirming discards a ready reply and restores board, history and feedback',function()
 local s=thinking();local initial=B.key(s.initial,'red',false)
 S.action(s,'UndoButton');S.update(s,.3);S.update(s,.3);assert(s.ready)
 local version=s.version;S.action(s,'ConfirmYes')
 assert(not s.modal and s.moves==0 and s.turn=='red' and #s.history==0 and s.version==version+1)
 assert(not s.job and not s.reply and not s.ready and not s.lastAiMove and s.aiCounter.value==0)
 assert(s.red==0 and B.key(s.board,'red',false)==initial)
 S.action(s,'ConfirmYes');S.update(s,20);assert(s.moves==0 and s.version==version+1)
end)
check('confirming during a real unfinished search cancels and restores it',function()
 local s=S.new();S.start(s,'custom');S.square(s,55);S.square(s,46);S.update(s,.01)
 local job=s.job;assert(job and not job.done);S.action(s,'UndoButton');assert(s.job==job and not job.done)
 S.action(s,'ConfirmYes');assert(job.done and job.restored and not s.job and s.moves==0 and not s.modal)
end)
check('completed pairs require confirmation and still undo only one player action',function()
 local s=thinking();S.update(s,.3);S.update(s,.3);assert(s.moves==2)
 local board=B.key(s.board,'red',false);S.action(s,'UndoButton');assert(s.moves==2)
 S.action(s,'ConfirmNo');assert(s.moves==2 and B.key(s.board,'red',false)==board)
 S.action(s,'UndoButton');S.action(s,'ConfirmYes');assert(s.moves==0 and s.turn=='red')
end)
check('empty history stays informative; resign and menu confirmations retain their meaning',function()
 local s=S.new();S.start(s,'fast');S.action(s,'UndoButton');assert(not s.modal and s.status=='尚無棋步可悔')
 S.action(s,'ResignButton');S.action(s,'ConfirmYes');assert(s.scene=='result' and s.resultReason=='主動認輸')
 S.action(s,'RestartButton');S.action(s,'ModeButton');S.action(s,'ConfirmYes');assert(s.scene=='mode-select')
end)
assert(failures==0,tostring(failures)..' undo confirmation regressions failed')
