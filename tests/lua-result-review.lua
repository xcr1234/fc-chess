local S=require('game.session')
local B=require('game.board')
require('app.log').enabled=false
local failures=0
local function check(name,fn)local ok,err=pcall(fn);print((ok and 'PASS ' or 'FAIL ')..name..(ok and '' or ': '..tostring(err)));if not ok then failures=failures+1 end end
local function board(rows)local b={} for i=1,90 do b[i]='' end for _,p in ipairs(rows) do b[B.index(p[1],p[2])]=p[3] end return b end
local function win()
 local s=S.new();S.start(s,'difficult',board({{3,9,'K'},{4,0,'k'},{4,5,'R'}}));s.aiInput='hold';S.square(s,B.index(4,5));S.square(s,B.index(4,0));assert(s.scene=='result');return s
end
local function confirmUndo(s)S.action(s,'UndoButton');assert(s.modal=='undo');S.action(s,'ConfirmYes')end
check('winning result can return to a frozen final board without selecting or moving',function()
 local s=win();local b=B.key(s.board,s.turn,s.custom);local red=s.red;local count=s.moveSoundSequence
 S.action(s,'ReturnBoardButton');assert(s.scene=='result-review' and s.status=='本局已结束，悔棋后可继续')
 S.square(s,B.index(4,0));S.square(s,B.index(4,1));S.update(s,100)
 assert(not s.selected and s.moves==1 and s.red==red and s.moveSoundSequence==count and B.key(s.board,s.turn,s.custom)==b)
 assert(not S.commit(s,{B.index(4,0),B.index(4,1)}));assert(not s.job and not s.reply)
end)
check('confirming undo after victory restores both kings and permits another move',function()
 local s=win();S.action(s,'ReturnBoardButton');local sequence=s.moveSoundSequence;confirmUndo(s)
 assert(s.scene=='player-turn' and s.turn=='red' and s.moves==0 and s.red==0 and not s.resultTitle and not s.resultReason)
 assert(s.board[B.index(4,0)]=='k' and s.board[B.index(4,5)]=='R' and s.moveSoundSequence==sequence)
 S.square(s,B.index(4,5));S.square(s,B.index(5,5));assert(s.moves==1 and s.board[B.index(5,5)]=='R')
end)
check('defeat review undoes the final red and black pair and restores prior feedback',function()
 local s=S.new();S.start(s,'difficult',board({{3,9,'K'},{4,0,'k'},{0,6,'P'},{3,8,'r'}}))
 s.aiInput={computeSeconds=.1,waitSeconds=0,replySequence={{3,8,3,9}}};S.square(s,B.index(0,6));S.square(s,B.index(0,5));S.update(s,.2);assert(s.scene=='result' and s.moves==2)
 S.action(s,'ReturnBoardButton');confirmUndo(s)
 assert(s.scene=='player-turn' and s.moves==0 and s.board[B.index(3,9)]=='K' and s.board[B.index(3,8)]=='r' and s.board[B.index(0,6)]=='P')
 assert(not s.lastAiMove and not s.job and not s.reply and s.aiCounter.value==0)
end)
check('declining undo keeps final board frozen and resign cannot create another result',function()
 local s=win();S.action(s,'ReturnBoardButton');local b=B.key(s.board,s.turn,false)
 S.action(s,'UndoButton');S.update(s,50);S.action(s,'ConfirmNo');S.action(s,'ResignButton')
 assert(s.scene=='result-review' and not s.modal and s.moves==1 and B.key(s.board,s.turn,false)==b)
 S.action(s,'ModeButton');assert(s.modal=='menu');S.action(s,'ConfirmNo');assert(s.scene=='result-review')
 S.action(s,'ModeButton');S.action(s,'ConfirmYes');assert(s.scene=='mode-select')
end)
check('resigned unfinished AI remains cancelled; undo can continue from its history',function()
 local s=S.new();S.start(s,'custom');S.square(s,55);S.square(s,46);S.update(s,.01);local job=s.job;assert(job)
 S.action(s,'ResignButton');S.action(s,'ConfirmYes');assert(job.done and job.restored)
 S.action(s,'ReturnBoardButton');S.update(s,100);assert(s.moves==1 and not s.job and not s.reply)
 confirmUndo(s);assert(s.scene=='player-turn' and s.moves==0 and s.custom and not s.job)
end)
check('empty-history resignation can be viewed but cannot resume without an undo',function()
 local s=S.new();S.start(s,'fast');S.action(s,'ResignButton');S.action(s,'ConfirmYes');S.action(s,'ReturnBoardButton')
 assert(s.scene=='result-review' and s.status=='本局已结束');S.action(s,'UndoButton');assert(not s.modal and s.status=='尚无棋步可悔' and s.scene=='result-review')
 S.square(s,55);assert(not s.selected and s.moves==0)
end)
check('return is available only from results; restart still preserves lineup and audio',function()
 local s=S.new();S.action(s,'ReturnBoardButton');assert(s.scene=='mode-select');S.start(s,'custom');s.audio.sfx=false;s.audio.volume=70
 S.action(s,'ReturnBoardButton');assert(s.scene=='player-turn');S.action(s,'ResignButton');S.action(s,'ConfirmYes');S.action(s,'RestartButton')
 assert(s.scene=='player-turn' and s.mode=='custom' and #s.history==0 and not s.resultTitle and s.audio.volume==70 and not s.audio.sfx)
end)
assert(failures==0,tostring(failures)..' result review failures')
