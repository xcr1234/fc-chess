import fs from 'node:fs';
const data=JSON.parse(fs.readFileSync('assets/audio/music-catalog.json','utf8'));
const ids=new Set();
for(const [id,name,seconds,category] of data.rows){
 if(!Number.isInteger(id)||ids.has(id)||typeof name!=='string'||!name||!(seconds>0)||!Number.isInteger(category)||!data.categories[category])throw new Error('Invalid music row '+id);
 ids.add(id);
}
for(const id of [10167,10161,10029])if(!ids.has(id))throw new Error('Missing recommended track '+id);
fs.mkdirSync('src/audio',{recursive:true});
fs.writeFileSync('src/audio/catalog.lua','-- Generated by scripts/generate-audio-catalog.mjs; music IDs are not sound IDs.\nreturn {\n'+data.rows.map(([id,name,seconds,category])=>` {id=${id},name=${JSON.stringify(name)},seconds=${seconds},category=${category}},`).join('\n')+'\n}\n');
fs.writeFileSync('prototype/audio-catalog.js','// Generated from assets/audio/music-catalog.json.\nconst FCChessMusicCatalog = '+JSON.stringify(data.rows)+';\n');
console.log('Generated '+ids.size+' built-in music choices');
