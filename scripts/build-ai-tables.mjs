import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
const dir='third_party/xqwlight/';
const manifest=JSON.parse(fs.readFileSync(dir+'UPSTREAM.json','utf8'));
manifest.sha256['search.js']='62d0027e0537464fedd263a4a068cedd180556682d19de8eb99e23d40006dd24';
for(const [name,hash] of Object.entries(manifest.sha256)) {
 const raw=fs.readFileSync(dir+name,'utf8');
 const text=name==='LICENSE'?raw.replaceAll('\r\n','\n'):raw.replaceAll('\r\n','\n').trimEnd()+'\n';
 if(createHash('sha256').update(text).digest('hex')!==hash)throw Error('Upstream checksum: '+name);
}
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync(dir+'position.js','utf8'),ctx);
let out='-- SPDX-License-Identifier: GPL-2.0-or-later\n-- XQWLight JavaScript 1.0, Morning Yellow, Copyright (C) 2004-2012 www.xqbase.com\n-- Generated by scripts/build-ai-tables.mjs from the pinned upstream.\nlocal M={value={},key={},lock={}}\n';
for(let side=0;side<2;side++)for(let kind=0;kind<7;kind++) {
 const pc=8+side*8+kind,adjust=side*7+kind;
 for(const [field,arr] of [['value',ctx.PIECE_VALUE[kind]],['key',ctx.PreGen_zobristKeyTable[adjust]],['lock',ctx.PreGen_zobristLockTable[adjust]]]) {
  const cells=[];
  for(let r=3;r<=12;r++)for(let f=3;f<=11;f++) {
   const sq=r*16+f;
   cells.push(`[${sq}]=${field==='value'?arr[side?254-sq:sq]:arr[sq]&0x7fffffff}`);
  }
  out+=`M.${field}[${pc}]={${cells.join(',')}}\n`;
 }
}
out+=`M.sideKey=${ctx.PreGen_zobristKeyPlayer&0x7fffffff}\nM.sideLock=${ctx.PreGen_zobristLockPlayer&0x7fffffff}\nreturn M\n`;
const path='src/game/ai/tables.lua';
if(process.argv.includes('--check')){if(fs.readFileSync(path,'utf8')!==out)throw Error('Stale AI tables');}
else{fs.writeFileSync(path,out);fs.writeFileSync(dir+'UPSTREAM.json',JSON.stringify(manifest,null,2)+'\n');}
console.log('PASS pinned JS checksums and generated evaluation/Zobrist tables');
